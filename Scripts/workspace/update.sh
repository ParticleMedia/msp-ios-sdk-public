  DEMOAPP_DIR="$ROOT_DIR/Examples/MSPDemoApp"
  DEMOAPP_REL="Examples/MSPDemoApp"
  DEMOAPP_PODS_XCCONFIG_DEBUG_REL="$DEMOAPP_PODS_XCCONFIG_DEBUG_REL_EXAMPLES"
