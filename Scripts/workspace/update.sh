# Helper to check if a package exists.
package_exists() {
  local name="$1"
  if [[ ${#PACKAGE_NAMES[@]-0} -eq 0 ]]; then
    return 1
  fi
  for candidate in "${PACKAGE_NAMES[@]-}"; do
    if [[ "$candidate" == "$name" ]]; then
      return 0
    fi
  done
  return 1
}

