  DEMOAPP_DIR="$ROOT_DIR/MSPDemoApp"
  DEMOAPP_REL="MSPDemoApp"
  DEMOAPP_PODS_XCCONFIG_DEBUG_REL="$DEMOAPP_PODS_XCCONFIG_DEBUG_REL_ROOT"
  DEMOAPP_PODS_XCCONFIG_RELEASE_REL="$DEMOAPP_PODS_XCCONFIG_RELEASE_REL_ROOT"
  PODS_ROOT_REL='$(SRCROOT)/../Pods'
