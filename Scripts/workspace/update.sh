# Generate the workspace specification so xcodegen can rebuild the .xcworkspace.
PROJECTS=()
while IFS= read -r proj; do
  PROJECTS+=("$proj")
done < <(find "$ROOT_DIR" -name '*.xcodeproj' \
  ! -path '*/DerivedData/*' ! -path '*/Pods/Pods.xcodeproj/*' \
  -print | LC_ALL=C sort)

pods_detected=0
{
  echo "workspace:"
  echo "  name: msp-ios-sdk"
  echo "  projects:"
  echo "    - name: MSPDemoApp"
  echo "      path: ${DEMOAPP_PROJECT_REL_PATH}"
  echo "      type: file"
  for proj in ${PROJECTS[@]+"${PROJECTS[@]}"}; do
    rel="${proj#$ROOT_DIR/}"
    # Skip the generated MSPDemoApp project - it will be created from the spec above.
    if [[ "$rel" == "$DEMOAPP_XCODEPROJ_REL" ]]; then
      continue
    fi
    if [[ "$rel" == "Pods/Pods.xcodeproj" ]]; then
      pods_detected=1
    fi
    project_name="$(basename "${rel%.*}")"
    echo "    - name: ${project_name}"
    echo "      path: ${rel}"
    echo "      type: file"
  done
  # Include Pods.xcodeproj if it exists (legacy mode, not used with :generate_multiple_pod_projects => true)
  if [[ $pods_detected -eq 0 ]] && [[ -d "$ROOT_DIR/Pods/Pods.xcodeproj" ]]; then
    echo "    - name: Pods"
    echo "      path: Pods/Pods.xcodeproj"
    echo "      type: file"
  fi
} > "$WORKSPACE_SPEC"

# Regenerate the .xcworkspace XML for Xcode consumers
mkdir -p "$WORKSPACE_PATH"
{
  cat <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<Workspace
   version = "1.0">
XML
  cat <<XML
   <FileRef
      location = "group:${DEMOAPP_XCODEPROJ_REL}">
   </FileRef>
XML
  for proj in ${PROJECTS[@]+"${PROJECTS[@]}"}; do
    rel="${proj#$ROOT_DIR/}"
    if [[ "$rel" == "$DEMOAPP_XCODEPROJ_REL" ]]; then
      continue
    fi
    cat <<XML
   <FileRef
      location = "group:${rel}">
   </FileRef>
XML
  done
  echo "</Workspace>"
} > "$WORKSPACE_DATA"

# R029e: Use xcodegen.sh module if available, fallback to direct call
if command -v xcodegen_generate &>/dev/null; then
  echo "$LOG_PREFIX Running xcodegen generate via xcodegen.sh module"
  if ! xcodegen_generate "$PROJECT_SPEC" "$(dirname "$PROJECT_SPEC")"; then
    echo "$LOG_PREFIX xcodegen failed. Ensure version 2.38.0+ is installed (run 'brew upgrade xcodegen')." >&2
  fi
else
  # Fallback to direct xcodegen call
  XCODEGEN_BIN="$(command -v xcodegen || true)"
  if [[ -z "$XCODEGEN_BIN" ]]; then
    echo "$LOG_PREFIX xcodegen is not installed. Install via 'brew install xcodegen' (2.38.0+ required) and re-run this script." >&2
  else
    echo "$LOG_PREFIX Running xcodegen generate"
    if ! "$XCODEGEN_BIN" generate --spec "$PROJECT_SPEC"; then
      echo "$LOG_PREFIX xcodegen failed. Ensure version 2.38.0+ is installed (run 'brew upgrade xcodegen')." >&2
    fi
  fi
fi

if [[ -f "$ROOT_DIR/Gemfile" ]]; then
  if [[ -n "${CI:-}" ]]; then
    echo "$LOG_PREFIX Running bundle exec pod install"
    if ! (cd "$ROOT_DIR" && bundle exec pod install); then
      echo "$LOG_PREFIX bundle exec pod install failed; please rerun locally." >&2
    fi
  else
    echo "$LOG_PREFIX Skipping pod install (run 'bundle exec pod install' locally to update Pods)."
  fi
fi

echo "$LOG_PREFIX Workspace spec -> $WORKSPACE_SPEC"
echo "$LOG_PREFIX Project spec -> $PROJECT_SPEC"
echo "$LOG_PREFIX SwiftPM packages -> $SWIFTPM_JSON"
